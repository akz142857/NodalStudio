WITH target AS (
    SELECT c.*, format('%I.%I', n.nspname, c.relname) AS qualified_name,
           CASE WHEN c.relkind = 'f' THEN 'FOREIGN TABLE' ELSE 'TABLE' END AS object_type
    FROM pg_class AS c
    JOIN pg_namespace AS n ON n.oid = c.relnamespace
    WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind IN ('r', 'p', 'f')
      AND has_schema_privilege(n.oid, 'USAGE')
      AND has_table_privilege(c.oid, 'SELECT')
), parents AS (
    SELECT string_agg(format('%I.%I', n.nspname, p.relname), ', ' ORDER BY i.inhseqno) AS names
    FROM target AS t
    JOIN pg_inherits AS i ON i.inhrelid = t.oid
    JOIN pg_class AS p ON p.oid = i.inhparent
    JOIN pg_namespace AS n ON n.oid = p.relnamespace
), columns AS (
    SELECT a.attnum, a.attname, col_description(t.oid, a.attnum) AS comment,
           format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
           || COALESCE((SELECT ' OPTIONS (' ||
               string_agg(format('%I %L', option_name, option_value), ', ' ORDER BY option_name)
               || ')' FROM pg_options_to_table(a.attfdwoptions)), '')
           || CASE WHEN a.attcollation <> ty.typcollation AND co.oid IS NOT NULL
               THEN format(' COLLATE %I.%I', ns.nspname, co.collname) ELSE '' END
           || CASE a.attidentity
               WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
               WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
               ELSE CASE
                   WHEN a.attgenerated <> '' THEN format(
                       ' GENERATED ALWAYS AS (%s) %s', pg_get_expr(d.adbin, d.adrelid),
                       CASE a.attgenerated WHEN 'v' THEN 'VIRTUAL' ELSE 'STORED' END)
                   WHEN d.oid IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
                   ELSE '' END
               END
           || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END AS definition,
           a.attislocal
    FROM target AS t
    JOIN pg_attribute AS a ON a.attrelid = t.oid
    JOIN pg_type AS ty ON ty.oid = a.atttypid
    LEFT JOIN pg_attrdef AS d ON d.adrelid = t.oid AND d.adnum = a.attnum
    LEFT JOIN pg_collation AS co ON co.oid = a.attcollation
    LEFT JOIN pg_namespace AS ns ON ns.oid = co.collnamespace
    WHERE a.attnum > 0 AND NOT a.attisdropped
), constraints AS (
    SELECT con.conname, con.conindid, con.contype,
           format('CONSTRAINT %I %s', con.conname, pg_get_constraintdef(con.oid)) AS definition
    FROM target AS t
    JOIN pg_constraint AS con ON con.conrelid = t.oid
    WHERE con.contype IN ('p', 'u', 'x', 'f', 'c') AND con.conislocal AND con.conparentid = 0
), fields AS (
    SELECT string_agg('    ' || definition, E',\n' ORDER BY position, name) AS definitions
    FROM (
        SELECT attnum AS position, attname AS name, definition FROM columns WHERE attislocal
        UNION ALL
        SELECT 32767, conname, definition FROM constraints
    ) AS entries
), foreign_settings AS (
    SELECT format(' SERVER %I', server.srvname) ||
           COALESCE((SELECT ' OPTIONS (' ||
               string_agg(format('%I %L', option_name, option_value), ', ' ORDER BY option_name)
               || ')' FROM pg_options_to_table(ft.ftoptions)), '') AS definition
    FROM target AS t
    JOIN pg_foreign_table AS ft ON ft.ftrelid = t.oid
    JOIN pg_foreign_server AS server ON server.oid = ft.ftserver
), statements AS (
    SELECT 0 AS section, '' AS name,
        format('CREATE %s%s %s', CASE WHEN t.relpersistence = 'u' THEN 'UNLOGGED ' ELSE '' END,
            t.object_type, t.qualified_name)
        || CASE WHEN t.relispartition
            THEN ' PARTITION OF ' || p.names || ' ' || pg_get_expr(t.relpartbound, t.oid)
            ELSE COALESCE(E' (\n' || f.definitions || E'\n)', ' ()')
                || COALESCE(' INHERITS (' || p.names || ')', '') END
        || CASE WHEN t.relkind = 'p' THEN ' PARTITION BY ' || pg_get_partkeydef(t.oid) ELSE '' END
        || COALESCE((SELECT definition FROM foreign_settings), '') || ';' AS statement
    FROM target AS t CROSS JOIN fields AS f CROSS JOIN parents AS p
    UNION ALL
    SELECT 1, con.conname, format('ALTER %s %s ADD %s;', t.object_type, t.qualified_name, con.definition)
    FROM target AS t CROSS JOIN constraints AS con
    WHERE t.relispartition
    UNION ALL
    SELECT 2, i.relname, pg_get_indexdef(idx.indexrelid) || ';'
    FROM target AS t
    JOIN pg_index AS idx ON idx.indrelid = t.oid
    JOIN pg_class AS i ON i.oid = idx.indexrelid
    WHERE idx.indisvalid AND NOT idx.indisprimary
      AND NOT EXISTS (SELECT FROM constraints AS con WHERE con.conindid = i.oid AND con.contype IN ('p', 'u', 'x'))
      AND NOT EXISTS (SELECT FROM pg_inherits WHERE inhrelid = i.oid)
    UNION ALL
    SELECT 3, '', format('COMMENT ON %s %s IS %L;', t.object_type, t.qualified_name, obj_description(t.oid, 'pg_class'))
    FROM target AS t WHERE obj_description(t.oid, 'pg_class') IS NOT NULL
    UNION ALL
    SELECT 4, a.attname, format('COMMENT ON COLUMN %s.%I IS %L;', t.qualified_name, a.attname, a.comment)
    FROM target AS t CROSS JOIN columns AS a WHERE a.comment IS NOT NULL
)
SELECT string_agg(statement, E'\n\n' ORDER BY section, name)
FROM statements
HAVING sum(octet_length(statement)::bigint + 2) <= $3::int
